"""
Expected-cost panel on the FULL benchmark D_N (not the monitoring panel).

The previous assets/metrics_export/expected_cost_tabular.tex was the 2026-04-13
monitoring run (n=300) with its confusion counts multiplied by 1199/300 and the
n column relabelled 1199. Linear rescaling preserves the panel's prevalence
(83.3% positive), so it cannot reproduce benchmark prevalence (56.9%).

This recomputes the panel from the real full-benchmark runs, using error_type
scores joined to traces, and prices each model from its own logged cost_usd.

  E_t[C](m) = C_t(m) + (C_FP * FP + C_FN * FN) / n
"""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).parent
OUT = ROOT / "assets" / "drift"
OUT.mkdir(parents=True, exist_ok=True)

C_FP, C_FN = 0.155, 0.031          # R = C_FP / C_FN = 5
BENCH_MIN = 400                     # a model-day with more unique items is D_N
EXCLUDE_DAYS = {"2026-07-13", "2026-07-14"}   # GEPA prompt-transfer evaluations

scores = pd.read_csv(ROOT / "streamlit_app" / "langfuse_scores.csv")
traces = pd.read_csv(ROOT / "streamlit_app" / "langfuse_traces.csv")
meta = traces[["id", "timestamp", "metadata.model", "metadata.custom_id"]]


def joined(name):
    d = scores[scores["name"] == name].merge(
        meta, left_on="traceId", right_on="id", how="left", suffixes=("_s", "_t"))
    d["model"] = d["metadata.model"].astype(str)
    d["item"] = d["metadata.custom_id"]
    d["day"] = pd.to_datetime(d["timestamp_t"]).dt.strftime("%Y-%m-%d")
    return d[(d.model != "nan") & d["item"].notna()]


err = joined("error_type").drop_duplicates(["model", "day", "item"])
cost = joined("cost_usd").drop_duplicates(["model", "day", "item"])
cost["usd"] = pd.to_numeric(cost["value"], errors="coerce")

size = err.groupby(["model", "day"])["item"].nunique()
bench = [(m, d) for (m, d), n in size.items()
         if n > BENCH_MIN and d not in EXCLUDE_DAYS]

# one benchmark run per model: the most recent qualifying day
chosen = {}
for m, d in sorted(bench):
    chosen[m] = d
print("full-benchmark runs used:")
for m, d in chosen.items():
    print(f"  {m:14s} {d}  n={size[(m, d)]}")

missing = sorted(set(err.model.unique()) - set(chosen))
rows = []
for m, d in chosen.items():
    g = err[(err.model == m) & (err.day == d)]
    c = g["stringValue"].value_counts()
    tp, fp = int(c.get("true_positive", 0)), int(c.get("false_positive", 0))
    tn, fn = int(c.get("true_negative", 0)), int(c.get("false_negative", 0))
    n = tp + fp + tn + fn
    cg = cost[(cost.model == m) & (cost.day == d)]["usd"]
    avg = float(cg.mean()) if len(cg) else float("nan")
    rows.append(dict(model=m, day=d, n=n, tp=tp, fp=fp, tn=tn, fn=fn,
                     prevalence=(tp + fn) / n,
                     accuracy=(tp + tn) / n,
                     avg_cost=avg,
                     ec=avg + (C_FP * fp + C_FN * fn) / n))

df = pd.DataFrame(rows).sort_values("ec")
df.to_csv(OUT / "expected_cost_benchmark.csv", index=False)

pd.set_option("display.width", 200)
print("\n" + df.round(6).to_string(index=False))
print(f"\nprevalence on D_N: {df.prevalence.min():.3f}-{df.prevalence.max():.3f}"
      f"  (panel D_n was 0.833)")
print(f"models without a benchmark run: {', '.join(missing)}")

body = "\n".join(
    f"    \\texttt{{{r.model}}} & {r.n} & {r.fp} & {r.fn} & {r.accuracy:.4f} & "
    f"{r.avg_cost:.6f} & {r.ec:.6f} \\\\"
    for r in df.itertuples())

(OUT / "expected_cost_benchmark.tex").write_text(
    f"""% Generated by expected_cost_benchmark.py -- real full-benchmark runs.
% C_FP = {C_FP}, C_FN = {C_FN}  (R = {C_FP / C_FN:.0f})
\\begin{{tabular}}{{lrrrrrr}}
    \\toprule
    Model & $n$ & FP & FN & Accuracy & Mean cost (USD) & $E_t[\\mathcal{{C}}]$ (USD) \\\\
    \\midrule
{body}
    \\bottomrule
\\end{{tabular}}
""")
print(f"\nwrote {OUT/'expected_cost_benchmark.tex'}")
