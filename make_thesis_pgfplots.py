"""
Emit native pgfplots figures for the thesis (replaces the matplotlib rasters/PDFs).

Writes self-contained .tex files that are \\input{} from the chapters, so the
figures use the document font, real LaTeX maths, and true vector output.

  fig_panel_trajectory.tex : panel accuracy over the monitoring period
  fig_gepa_trajectory.tex  : GEPA accepted-candidate vs running best
  fig_stability.tex        : per-comparison discordance over the period,
                             most / least stable models picked out

Colours are the validated categorical slots 1-3 (#2a78d6, #eb6834, #1baf7a)
plus the reference chrome greys.
"""
import json
from datetime import date
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).parent
OUT = ROOT / "assets" / "drift"
OUT.mkdir(parents=True, exist_ok=True)
PANEL_MAX = 400
FOCUS = "gpt-4.1-mini"
ORIGIN = date(2026, 3, 8)

PREAMBLE = r"""% Generated by make_thesis_pgfplots.py -- do not edit by hand.
\definecolor{vizblue}{HTML}{2A78D6}
\definecolor{vizorange}{HTML}{EB6834}
\definecolor{vizaqua}{HTML}{1BAF7A}
\definecolor{vizgrid}{HTML}{E1E0D9}
\definecolor{vizaxis}{HTML}{C3C2B7}
\definecolor{vizmuted}{HTML}{898781}
\definecolor{vizink}{HTML}{52514E}
"""

AXIS_STYLE = r"""        axis line style={vizaxis, line width=0.4pt},
        tick label style={vizmuted, font=\scriptsize},
        label style={vizink, font=\small},
        legend style={draw=none, fill=none, font=\scriptsize,
                      text=vizink, inner sep=1pt},
        grid=major,
        grid style={vizgrid, line width=0.4pt},
        axis x line*=bottom,
        axis y line*=left,
        ymajorgrids=true,
        xmajorgrids=false,
        clip=false,"""


def load():
    s = pd.read_csv(ROOT / "streamlit_app" / "langfuse_scores.csv")
    t = pd.read_csv(ROOT / "streamlit_app" / "langfuse_traces.csv")
    d = s[s["name"] == "accuracy"].merge(
        t[["id", "timestamp", "metadata.model", "metadata.custom_id"]],
        left_on="traceId", right_on="id", how="left", suffixes=("_s", "_t"))
    d["model"] = d["metadata.model"].astype(str)
    d["item"] = d["metadata.custom_id"]
    d["correct"] = d["value"].astype(int)
    d["date"] = pd.to_datetime(d["timestamp_t"]).dt.tz_localize(None).dt.normalize()
    d = d[(d.model != "nan") & d["item"].notna()]
    return d.drop_duplicates(["model", "date", "item"])


# ------------------------------------------------------------ trajectory
d = load()
mon = d[d.groupby(["model", "date"])["item"].transform("nunique") <= PANEL_MAX]
series = mon.groupby(["model", "date"])["correct"].mean().rename("acc").reset_index()
long = series.groupby("model")["date"].size()
series = series[series.model.isin(long[long >= 10].index)].copy()
series["x"] = (series.date.dt.date - ORIGIN).apply(lambda t: t.days)

xmax = int(series.x.max())
ticks, labels = [], []
ticks.append(0); labels.append("8 Mar")
for m, lab in [(4, "Apr"), (5, "May"), (6, "Jun"), (7, "Jul"), (8, "Aug")]:
    off = (date(2026, m, 1) - ORIGIN).days
    if 0 <= off <= xmax + 6:
        ticks.append(off)
        labels.append(f"1 {lab}")


def coords(g):
    return " ".join(f"({r.x},{r.acc:.4f})" for r in g.sort_values("x").itertuples())


others = [coords(g) for m, g in series[series.model != FOCUS].groupby("model")]
focus = series[series.model == FOCUS].sort_values("x")
dip = focus.loc[focus.acc.idxmin()]

body = [PREAMBLE, r"\begin{tikzpicture}", r"    \begin{axis}[",
        r"        width=\linewidth, height=5.4cm,",
        f"        xmin=-3, xmax={xmax + 3}, ymin=0.46, ymax=1.005,",
        f"        xtick={{{','.join(map(str, ticks))}}},",
        f"        xticklabels={{{','.join(labels)}}},",
        r"        ytick={0.5,0.6,0.7,0.8,0.9,1.0},",
        r"        yticklabel style={/pgf/number format/fixed,"
        r" /pgf/number format/fixed zerofill,"
        r" /pgf/number format/precision=1},",
        r"        ylabel={panel accuracy},",
        r"        legend columns=2,",
        r"        legend style={at={(0.5,-0.20)}, anchor=north,"
        r" /tikz/every even column/.append style={column sep=8pt}},",
        AXIS_STYLE, r"    ]"]

for c in others:
    body.append(r"    \addplot[vizmuted, line width=0.35pt, opacity=0.55, "
                f"forget plot] coordinates {{{c}}};")
body.append(r"    \addplot[vizblue, line width=1.1pt, mark=*, mark size=1.0pt, "
            f"mark options={{fill=vizblue, draw=vizblue}}] coordinates {{{coords(focus)}}};")
body.append(r"    \addlegendentry{\texttt{gpt-4.1-mini}}")
# legend-only entry: no coordinates, so it cannot affect the bounding box
body.append(r"    \addlegendimage{vizmuted, line width=0.35pt, opacity=0.8}")
body.append(r"    \addlegendentry{other monitored models}")
body.append(
    f"    \\node[anchor=west, font=\\scriptsize, text=vizink, align=left] "
    f"at (axis cs:{int(dip.x) + 4},{dip.acc + 0.035:.3f}) "
    r"{22--23 March\\$-13$\,pp, $-28$\,pp};")
body += [r"    \end{axis}", r"\end{tikzpicture}"]
(OUT / "fig_panel_trajectory.tex").write_text("\n".join(body) + "\n")
print("wrote assets/drift/fig_panel_trajectory.tex")

# ------------------------------------------------------------ GEPA
run = json.load(open(ROOT / "prompt_optimization" / "runs" / "gpt-4.1-nano"
                     / "20260713-184939Z" / "gepa_result.json"))
val = run["val_aggregate_scores"]
best = pd.Series(val).cummax().tolist()
bi = run["best_idx"]
cv = " ".join(f"({i},{v:.4f})" for i, v in enumerate(val))
cb = " ".join(f"({i},{v:.4f})" for i, v in enumerate(best))

g = [PREAMBLE, r"\begin{tikzpicture}", r"    \begin{axis}[",
     r"        width=0.72\linewidth, height=4.6cm,",
     f"        xmin=-0.35, xmax={len(val) - 0.65}, ymin=0.64, ymax=0.815,",
     f"        xtick={{{','.join(str(i) for i in range(len(val)))}}},",
     r"        ytick={0.66,0.70,0.74,0.78},",
     r"        yticklabel style={/pgf/number format/fixed,"
     r" /pgf/number format/fixed zerofill,"
     r" /pgf/number format/precision=2},",
     r"        xlabel={accepted candidate index},",
     r"        ylabel={validation score},",
     r"        legend columns=2,",
     r"        legend style={at={(0.5,-0.26)}, anchor=north,"
     r" /tikz/every even column/.append style={column sep=8pt}},",
     AXIS_STYLE, r"    ]",
     f"    \\addplot[vizorange, line width=1.1pt] coordinates {{{cb}}};",
     r"    \addlegendentry{running best}",
     r"    \addplot[vizblue, line width=1.1pt, mark=*, mark size=1.4pt,"
     f" mark options={{fill=vizblue, draw=vizblue}}] coordinates {{{cv}}};",
     r"    \addlegendentry{accepted candidate}",
     f"    \\addplot[only marks, mark=*, mark size=2.6pt, vizblue, forget plot] "
     f"coordinates {{({bi},{val[bi]:.4f})}};",
     f"    \\node[anchor=south, font=\\scriptsize, text=vizink] "
     f"at (axis cs:{bi},{val[bi] + 0.006:.4f}) {{best: {val[bi]:.3f}}};",
     f"    \\node[anchor=south west, font=\\scriptsize, text=vizink] "
     f"at (axis cs:0,{val[0] + 0.004:.4f}) {{seed: {val[0]:.3f}}};",
     r"    \end{axis}", r"\end{tikzpicture}"]
(OUT / "fig_gepa_trajectory.tex").write_text("\n".join(g) + "\n")
print("wrote assets/drift/fig_gepa_trajectory.tex")
print(f"  seed={val[0]:.4f} best={val[bi]:.4f} idx={bi}")

# ------------------------------------------------------------ stability
MIN_COMPARISONS = 10   # a median over two or three points is not an estimate

res = pd.read_csv(OUT / "drift_comparisons.csv")
res["x"] = (pd.to_datetime(res.current).dt.date - ORIGIN).apply(lambda t: t.days)
counts = res.groupby("model").size()
res = res[res.model.isin(counts[counts >= MIN_COMPARISONS].index)]

rank = res.groupby("model").discordance.median().sort_values()
stable, churny = rank.index[0], rank.index[-1]
picked = {churny: "vizorange", "gpt-5-mini": "vizaqua", stable: "vizblue"}

sxmax = int(res.x.max())
sticks, slabels = [0], ["8 Mar"]
for m, lab in [(4, "Apr"), (5, "May"), (6, "Jun"), (7, "Jul")]:
    sticks.append((date(2026, m, 1) - ORIGIN).days)
    slabels.append(f"1 {lab}")


def disc_coords(g):
    return " ".join(f"({r.x},{r.discordance:.4f})"
                    for r in g.sort_values("x").itertuples())


s = [PREAMBLE, r"\begin{tikzpicture}", r"    \begin{axis}[",
     r"        width=\linewidth, height=6.4cm,",
     f"        xmin=-3, xmax={sxmax + 30}, ymin=0, ymax=0.345,",
     f"        xtick={{{','.join(map(str, sticks))}}},",
     f"        xticklabels={{{','.join(slabels)}}},",
     r"        ytick={0,0.05,0.10,0.15,0.20,0.25,0.30},",
     r"        yticklabel style={/pgf/number format/fixed,"
     r" /pgf/number format/fixed zerofill,"
     r" /pgf/number format/precision=2},",
     r"        ylabel={discordance $\hat\psi=(b+c)/n$},",
     r"        legend columns=2,",
     r"        legend style={at={(0.5,-0.20)}, anchor=north,"
     r" /tikz/every even column/.append style={column sep=8pt}},",
     AXIS_STYLE, r"    ]"]

for m, gg in res[~res.model.isin(picked)].groupby("model"):
    s.append(r"    \addplot[vizmuted, line width=0.35pt, opacity=0.55, "
             f"forget plot] coordinates {{{disc_coords(gg)}}};")

for m, colour in picked.items():
    gg = res[res.model == m].sort_values("x")
    s.append(f"    \\addplot[{colour}, line width=1.1pt, mark=*, mark size=1.0pt, "
             f"mark options={{fill={colour}, draw={colour}}}, forget plot] "
             f"coordinates {{{disc_coords(gg)}}};")
    last = gg.iloc[-1]
    s.append(f"    \\node[anchor=west, font=\\scriptsize, text=vizink] "
             f"at (axis cs:{int(last.x) + 3},{last.discordance:.4f}) "
             f"{{\\texttt{{{m}}}}};")

sig = res[(res.alert_raw == 1) & res.model.isin(picked)]
s.append(r"    \addplot[only marks, mark=o, mark size=2.4pt, "
         "draw=vizink, line width=0.5pt, forget plot] coordinates {"
         + " ".join(f"({r.x},{r.discordance:.4f})"
                    for r in sig.itertuples()) + "};")

s.append(r"    \addlegendimage{vizmuted, line width=0.35pt, opacity=0.8}")
s.append(r"    \addlegendentry{other monitored models}")
s.append(r"    \addlegendimage{only marks, mark=o, mark size=2.4pt,"
         r" draw=vizink, line width=0.5pt}")
s.append(r"    \addlegendentry{McNemar $p<0.05$, uncorrected}")

spike = res.loc[res.discordance.idxmax()]
s.append(f"    \\node[anchor=west, font=\\scriptsize, text=vizink, align=left] "
         f"at (axis cs:{int(spike.x) + 6},{spike.discordance - 0.012:.4f}) "
         f"{{\\texttt{{{spike.model}}}, 22--23~Mar\\\\"
         f"$\\Delta\\widehat{{A}}=-13$, $-28$\\,pp}};")

s += [r"    \end{axis}", r"\end{tikzpicture}"]
(OUT / "fig_stability.tex").write_text("\n".join(s) + "\n")
print("wrote assets/drift/fig_stability.tex")
print(f"  least stable {churny} ({rank.iloc[-1]:.3f}), "
      f"most stable {stable} ({rank.iloc[0]:.3f}), "
      f"{len(rank)} models, {len(res)} comparisons")
