"""
Cost-aware model-selection map for Chapter 4 (cost-aware deployment utility).

Reads the full-benchmark panel written by expected_cost_benchmark.py and draws
the region of the (R, lambda) plane in which each candidate minimises

    E_t[C](m) = C_t(m) + lambda * (R * FP_t(m) + FN_t(m)) / n,

with R = C_FP / C_FN and lambda = C_FN, i.e. exactly the parameterisation of
Section "Cost parameters under uncertainty". For a fixed R the expected cost is
affine in lambda, so the winner is the lower envelope of a set of lines and each
model wins on one contiguous lambda interval; sweeping R traces the break-even
boundaries of Section "Pairwise break-even analysis".

Output: assets/drift/fig_cost_decision_map.tex (native pgfplots, \\input{} from
the chapter). Shading is the sequential blue ramp ordered by the winner's own
inference cost -- moving away from the origin, the map buys more inference.
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).parent
OUT = ROOT / "assets" / "drift"
OUT.mkdir(parents=True, exist_ok=True)

R_MIN, R_MAX = 0.1, 100.0
L_MIN, L_MAX = 3e-3, 3.0
N_R = 90                              # R samples used to trace the boundaries
C_FP_REF, C_FN_REF = 0.155, 0.031     # the chapter's worked operating point

# sequential blue ramp, light -> dark (references/palette.md steps 100-350)
RAMP = ["cde2fb", "b7d3f6", "9ec5f4", "86b6ef", "6da7ec", "5598e7"]
DARK_LABEL_FROM = 4                   # ramp index at which ink flips to black

PREAMBLE = r"""% Generated by make_cost_decision_map.py -- do not edit by hand.
\definecolor{vizgrid}{HTML}{E1E0D9}
\definecolor{vizaxis}{HTML}{C3C2B7}
\definecolor{vizmuted}{HTML}{898781}
\definecolor{vizink}{HTML}{52514E}
"""


def envelope(const, slope):
    """Lower envelope of lines y = const + lambda * slope over lambda > 0.

    Returns [(index, lambda_lo, lambda_hi), ...] ordered by lambda.
    """
    order = sorted(range(len(const)), key=lambda i: (const[i], slope[i]))
    segs = [(order[0], 0.0, np.inf)]
    for i in order[1:]:
        while segs:
            j, lo, _ = segs[-1]
            if slope[i] >= slope[j]:      # never overtakes the incumbent
                i = None
                break
            cross = (const[i] - const[j]) / (slope[j] - slope[i])
            if cross <= lo:               # incumbent is fully shadowed
                segs.pop()
                continue
            segs[-1] = (j, lo, cross)
            segs.append((i, cross, np.inf))
            break
        if i is None:
            continue
    return segs


def dominated(df):
    """Candidates beaten on inference cost, FP rate and FN rate simultaneously."""
    out = []
    for a in df.itertuples():
        for b in df.itertuples():
            if a.model == b.model:
                continue
            if (b.avg_cost <= a.avg_cost and b.fp_rate <= a.fp_rate
                    and b.fn_rate <= a.fn_rate
                    and (b.avg_cost < a.avg_cost or b.fp_rate < a.fp_rate
                         or b.fn_rate < a.fn_rate)):
                out.append((a.model, b.model))
                break
    return out


df = pd.read_csv(OUT / "expected_cost_benchmark.csv")
df["fp_rate"] = df.fp / df.n
df["fn_rate"] = df.fn / df.n

print("dominated candidates (removed before the sweep):")
for loser, winner in dominated(df):
    print(f"  {loser:14s} dominated by {winner}")
df = df[~df.model.isin({loser for loser, _ in dominated(df)})].reset_index(drop=True)

grid_r = np.logspace(np.log10(R_MIN), np.log10(R_MAX), N_R)
const = df.avg_cost.to_numpy()

# Along the envelope, lambda ascends exactly as inference cost ascends: the
# lambda->0 winner is the cheapest model, and every later winner buys more
# inference to shed error. Order the candidates that way once, then record for
# each of them the upper edge of the band it occupies at each R (equal to the
# previous model's upper edge where it never wins).
order = list(df.sort_values("avg_cost").model)
upper = {m: np.full(N_R, L_MIN) for m in order}
for col, r in enumerate(grid_r):
    slope = (r * df.fp_rate + df.fn_rate).to_numpy()
    top = {df.model.iloc[i]: min(hi, L_MAX)
           for i, _, hi in envelope(const, slope)}
    edge = L_MIN
    for m in order:
        edge = max(edge, top.get(m, edge))
        upper[m][col] = edge

winners = [m for m in order
           if upper[m].max() > L_MIN
           and (order.index(m) == 0
                or (upper[m] > upper[order[order.index(m) - 1]] + 1e-12).any())]

# shade by the winner's own inference cost: the further from the origin, the
# more inference the map tells you to buy
if len(winners) > len(RAMP):
    raise SystemExit(f"{len(winners)} winners but only {len(RAMP)} ramp steps")
rank = {m: i for i, m in enumerate(winners)}

print(f"\nwinners over R in [{R_MIN:g}, {R_MAX:g}], "
      f"lambda in [{L_MIN:g}, {L_MAX:g}] USD:")
for m in winners:
    print(f"  {m:14s} shade #{RAMP[rank[m]]}  mean cost "
          f"{float(df.loc[df.model == m, 'avg_cost'].iloc[0]):.6f} USD")

# ---------------------------------------------------------------- rendering
# Paint most-expensive first, each filling from the bottom of the axis up to
# its own upper edge; cheaper models overpaint the lower part. The regions then
# tile exactly, with no hairline seams and no gaps at the boundaries.
regions = []
for m in reversed(winners):
    top = " ".join(f"({r:.5g},{u:.6g})" for r, u in zip(grid_r, upper[m]))
    regions.append(
        f"    \\addplot[fill=cost{rank[m]}, draw=none, forget plot]\n"
        f"        coordinates {{({R_MIN:g},{L_MIN:g}) {top} "
        f"({R_MAX:g},{L_MIN:g})}} -- cycle;")
# hairline on each break-even boundary, so the switch is visible where two
# adjacent shades are close
for m in winners[:-1]:
    edge = upper[m]
    if edge.max() >= L_MAX:
        edge = np.minimum(edge, L_MAX)
    regions.append(
        "    \\addplot[white, line width=0.5pt, forget plot]\n"
        "        coordinates {"
        + " ".join(f"({r:.5g},{u:.6g})" for r, u in zip(grid_r, edge)) + "};")

# label geometry, in cm on the printed page (axis box minus tick/axis labels)
PLOT_W, PLOT_H = 11.8, 7.1
DEC_X = np.log10(R_MAX) - np.log10(R_MIN)
DEC_Y = np.log10(L_MAX) - np.log10(L_MIN)
CHAR_W, LINE_H, PAD = 0.145, 0.30, 0.10     # \scriptsize\ttfamily


def place(m, scale=1.0):
    """Largest axis-aligned box inscribed in a model's band, in log space."""
    lo = upper[order[order.index(m) - 1]] if order.index(m) else np.full(N_R, L_MIN)
    hi = upper[m]
    need_w = scale * len(m) * CHAR_W + 2 * PAD
    need_h = scale * LINE_H + 2 * PAD
    best = None
    for i in range(N_R):
        top, bot = np.inf, 0.0
        for j in range(i, N_R):
            top, bot = min(top, hi[j]), max(bot, lo[j])
            if top <= bot:
                break
            w = (np.log10(grid_r[j]) - np.log10(grid_r[i])) / DEC_X * PLOT_W
            h = (np.log10(top) - np.log10(bot)) / DEC_Y * PLOT_H
            for rot, (nw, nh) in ((0, (need_w, need_h)), (90, (need_h, need_w))):
                margin = min(w - nw, h - nh)
                if best is None or margin > best[0]:
                    best = (margin, rot, i, j, bot, top)
    margin, rot, i, j, bot, top = best
    r = 10 ** ((np.log10(grid_r[i]) + np.log10(grid_r[j])) / 2)
    lam = 10 ** ((np.log10(bot) + np.log10(top)) / 2)
    return r, lam, rot, margin


labels, outside = [], []
for m in winners:
    size, r, lam, rot, margin = "scriptsize", *place(m)
    if margin < 0:                       # narrow region: retry one size down
        size, (r, lam, rot, margin) = "tiny", place(m, scale=0.82)
    ink = "black" if rank[m] >= DARK_LABEL_FROM else "vizink"
    turn = ", rotate=90" if rot else ""
    if margin < 0:
        outside.append(m)
    labels.append(
        f"    \\node[font=\\{size}, text={ink}, inner sep=1pt{turn}] "
        f"at (axis cs:{r:.5g},{lam:.6g}) {{\\texttt{{{m}}}}};")
if outside:
    print(f"warning: no room for an in-region label: {', '.join(outside)}")

ref_r, ref_lam = C_FP_REF / C_FN_REF, C_FN_REF
tex = PREAMBLE + "".join(
    f"\\definecolor{{cost{i}}}{{HTML}}{{{c.upper()}}}\n" for i, c in enumerate(RAMP))
tex += rf"""
\begin{{tikzpicture}}
    \begin{{axis}}[
        width=0.86\linewidth, height=8.3cm,
        xmode=log, ymode=log,
        xmin={R_MIN}, xmax={R_MAX}, ymin={L_MIN}, ymax={L_MAX},
        xlabel={{error-cost asymmetry $R=C_{{\mathrm{{FP}}}}/C_{{\mathrm{{FN}}}}$}},
        ylabel={{error severity $\lambda=C_{{\mathrm{{FN}}}}$ [USD]}},
        axis line style={{vizaxis, line width=0.4pt}},
        tick label style={{vizmuted, font=\scriptsize}},
        label style={{vizink, font=\small}},
        grid=major,
        grid style={{vizgrid, line width=0.4pt}},
        axis on top=true,
        clip=true,
    ]
{chr(10).join(regions)}
{chr(10).join(labels)}
    \addplot[only marks, mark=*, mark size=1.9pt, black, forget plot]
        coordinates {{({ref_r:.5g},{ref_lam:.6g})}};
    \node[anchor=south east, font=\scriptsize, text=black, inner sep=3pt]
        at (axis cs:{ref_r:.5g},{ref_lam:.6g})
        {{$C_{{\mathrm{{FP}}}}={C_FP_REF}$, $C_{{\mathrm{{FN}}}}={C_FN_REF}$
          (Table~\ref{{tab:expected-cost-snapshot}})}};
    \end{{axis}}
\end{{tikzpicture}}
"""

(OUT / "fig_cost_decision_map.tex").write_text(tex)
print(f"\nwrote {OUT / 'fig_cost_decision_map.tex'}")

# the worked operating point, for the chapter text
slope = (ref_r * df.fp_rate + df.fn_rate).to_numpy()
ec = const + ref_lam * slope
best = df.model.iloc[int(np.argmin(ec))]
print(f"at R={ref_r:g}, lambda={ref_lam:g}: argmin = {best}")
for idx, lo, hi in envelope(const, slope):
    print(f"  R={ref_r:g}: {df.model.iloc[idx]:14s} wins for lambda in "
          f"[{lo:.5g}, {hi:.5g}]")
